import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

import { MODES, VENDOR_DIR, WORKSPACE_PACKAGES } from "./constants.mjs";
import { buildTemplateManifest } from "./manifest.mjs";
import { vendorPackage } from "./pack.mjs";
import { findEscapingPaths, isCheckedFile, isCopied } from "./paths.mjs";
import { buildReadme, DEV_VARS_EXAMPLE } from "./texts.mjs";

/** Written into every generated folder; the generator only ever deletes a folder that carries it. */
export const MARKER_FILE = ".template-generated";

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));
const toPosix = (path) => path.split(sep).join("/");

/** Every file under `directory` (relative posix paths), skipping what `shouldSkip` rejects. */
const walk = (directory, shouldSkip = () => false, base = directory) => {
	const files = [];
	for (const entry of readdirSync(directory)) {
		const absolute = join(directory, entry);
		const path = toPosix(relative(base, absolute));
		if (shouldSkip(path)) continue;
		if (statSync(absolute).isDirectory()) files.push(...walk(absolute, shouldSkip, base));
		else files.push(path);
	}
	return files;
};

/** Escaping relative paths of every checked file under `root`, as `file: specifier`. */
export const scanForEscapingPaths = (root, prefix = "") =>
	walk(root, (path) => path.split("/").includes("node_modules")).flatMap((file) =>
		isCheckedFile(file)
			? findEscapingPaths(file, readFileSync(join(root, file), "utf8")).map((specifier) => `${prefix}${file}: ${specifier}`)
			: [],
	);

const prepareOutDir = (repoRoot, outDir) => {
	const root = resolve(repoRoot);
	if (root === outDir || root.startsWith(outDir + sep)) throw new Error(`Refusing to write into ${outDir}: it contains the repository`);
	if (!existsSync(outDir)) return mkdirSync(outDir, { recursive: true });
	const isEmpty = readdirSync(outDir).length === 0;
	if (!isEmpty && !existsSync(join(outDir, MARKER_FILE))) {
		throw new Error(`Refusing to overwrite ${outDir}: it is not empty and was not generated by this script (no ${MARKER_FILE})`);
	}
	rmSync(outDir, { recursive: true, force: true });
	mkdirSync(outDir, { recursive: true });
};

/**
 * Write a self-contained copy of `apps/storefront` (the Cloudflare template) to `outDir`.
 *
 * @param {{ repoRoot: string, outDir: string, mode?: string, sourceSha?: string }} options
 * @returns {{ outDir: string, mode: string, vendored: string[], files: number }}
 */
export const generateTemplate = ({ repoRoot, outDir, mode = MODES.VENDOR, sourceSha }) => {
	const out = resolve(outDir);
	const app = join(repoRoot, "apps", "storefront");
	const rootManifest = readJson(join(repoRoot, "package.json"));
	const storefront = readJson(join(app, "package.json"));

	prepareOutDir(repoRoot, out);

	for (const file of walk(app, (path) => !isCopied(path))) {
		mkdirSync(join(out, file, ".."), { recursive: true });
		cpSync(join(app, file), join(out, file));
	}

	const versions = {};
	const vendored = [];
	for (const [name, folder] of Object.entries(WORKSPACE_PACKAGES)) {
		const packageDir = join(repoRoot, "packages", folder);
		versions[name] = readJson(join(packageDir, "package.json")).version;
		if (mode !== MODES.VENDOR) continue;
		vendorPackage(packageDir, join(out, VENDOR_DIR, folder));
		vendored.push(folder);
	}

	const manifest = buildTemplateManifest(storefront, {
		mode,
		versions,
		packageManager: rootManifest.packageManager,
		nodeEngine: rootManifest.engines?.node,
		overrides: rootManifest.pnpm?.overrides,
	});
	writeFileSync(join(out, "package.json"), `${JSON.stringify(manifest, null, "\t")}\n`);
	writeFileSync(join(out, ".dev.vars.example"), DEV_VARS_EXAMPLE);
	writeFileSync(join(out, "README.md"), buildReadme({ mode, sourceSha }));
	cpSync(join(repoRoot, "LICENSE"), join(out, "LICENSE"));
	writeFileSync(join(out, MARKER_FILE), "Generated by `pnpm template:cloudflare` in zawoj/emdash-commerce. Do not edit.\n");

	const escaping = scanForEscapingPaths(out);
	if (escaping.length > 0) throw new Error(`The copy reaches outside its own folder:\n  ${escaping.join("\n  ")}`);

	return { outDir: out, mode, vendored, files: walk(out).length };
};
